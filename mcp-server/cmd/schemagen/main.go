// Command schemagen writes contracts/mcp/<tool>.json: each tool exactly as
// the server advertises it in tools/list, schemas inferred from the Go types.
// With -check it writes nothing and fails if the files are stale.
package main

import (
	"bytes"
	"context"
	"encoding/json"
	"flag"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"slices"
	"strings"

	"github.com/modelcontextprotocol/go-sdk/mcp"

	"github.com/7wik-pk/Matchday-Muse/mcp-server/internal/tools"
)

const comment = "GENERATED by mcp-server/cmd/schemagen from the Go types; do not edit. Run make gen."

func main() {
	out := flag.String("out", "../contracts/mcp", "output directory")
	check := flag.Bool("check", false, "fail if the files are stale instead of writing them")
	flag.Parse()

	files, err := generate(context.Background())
	if err != nil {
		log.Fatal(err)
	}
	if *check {
		if stale := diff(*out, files); len(stale) > 0 {
			fmt.Fprintf(os.Stderr, "contracts/mcp is stale (%s); run make gen\n", strings.Join(stale, ", "))
			os.Exit(1)
		}
		fmt.Printf("contracts/mcp up to date: %d tools\n", len(files))
		return
	}
	if err := os.MkdirAll(*out, 0o755); err != nil {
		log.Fatal(err)
	}
	for _, name := range orphans(*out, files) {
		if err := os.Remove(filepath.Join(*out, name)); err != nil {
			log.Fatal(err)
		}
	}
	for name, data := range files {
		if err := os.WriteFile(filepath.Join(*out, name), data, 0o644); err != nil {
			log.Fatal(err)
		}
	}
	fmt.Printf("wrote %d tools to %s\n", len(files), *out)
}

// generate lists the tools through a real client session, so the files hold
// what clients see, not a second rendering of the Go types.
func generate(ctx context.Context) (map[string][]byte, error) {
	srv := tools.NewServer(tools.Deps{}, tools.Version)
	st, ct := mcp.NewInMemoryTransports()
	if _, err := srv.Connect(ctx, st, nil); err != nil {
		return nil, err
	}
	client := mcp.NewClient(&mcp.Implementation{Name: "schemagen", Version: tools.Version}, nil)
	cs, err := client.Connect(ctx, ct, nil)
	if err != nil {
		return nil, err
	}
	defer cs.Close()
	res, err := cs.ListTools(ctx, nil)
	if err != nil {
		return nil, err
	}
	files := map[string][]byte{}
	for _, t := range res.Tools {
		data, err := json.Marshal(struct {
			Comment string `json:"$comment"`
			*mcp.Tool
		}{comment, t})
		if err != nil {
			return nil, err
		}
		var buf bytes.Buffer
		if err := json.Indent(&buf, data, "", "  "); err != nil {
			return nil, err
		}
		buf.WriteByte('\n')
		files[t.Name+".json"] = buf.Bytes()
	}
	return files, nil
}

func diff(dir string, files map[string][]byte) []string {
	stale := orphans(dir, files)
	for name, data := range files {
		if old, err := os.ReadFile(filepath.Join(dir, name)); err != nil || !bytes.Equal(old, data) {
			stale = append(stale, name)
		}
	}
	slices.Sort(stale)
	return stale
}

// orphans are files in dir for tools that no longer exist.
func orphans(dir string, files map[string][]byte) []string {
	existing, _ := filepath.Glob(filepath.Join(dir, "*.json"))
	var out []string
	for _, path := range existing {
		if _, ok := files[filepath.Base(path)]; !ok {
			out = append(out, filepath.Base(path))
		}
	}
	return out
}
