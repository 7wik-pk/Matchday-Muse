// Generates the frontend's TypeScript types from the WebSocket and pipeline
// schemas. With --check, exits non-zero if the committed file is stale
// instead of writing it.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compile } from 'json-schema-to-typescript';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, '..', 'frontend', 'src', 'app', 'contracts', 'contracts.ts');
const check = process.argv.includes('--check');

// One root that references every top-level schema, so each shared type is
// emitted once instead of once per file that uses it.
const entry = {
  title: 'ContractRoots',
  description: 'Code generation entry point only; import the named types instead.',
  type: 'object',
  properties: {
    client: { $ref: 'client-message.json' },
    server: { $ref: 'server-message.json' },
    script: { $ref: 'mock-script.json' },
    takes: { $ref: 'mock-takes.json' },
  },
  additionalProperties: false,
};

const banner = `// GENERATED by contracts/scripts/gen-ts.mjs from contracts/ws and contracts/pipeline.
// Do not edit; change the schemas and run \`make gen\`.
`;

const ts = await compile(entry, 'ContractRoots', {
  cwd: join(root, 'ws'),
  bannerComment: banner,
  additionalProperties: false,
  ignoreMinAndMaxItems: true,
  style: { singleQuote: true, printWidth: 100 },
});

const target = relative(join(root, '..'), out);
if (check) {
  let current = '';
  try {
    current = readFileSync(out, 'utf8');
  } catch {}
  if (current !== ts) {
    console.error(`FAIL ${target} is stale; run \`make gen\``);
    process.exit(1);
  }
  console.log(`ok: ${target} is up to date`);
} else {
  writeFileSync(out, ts);
  console.log(`wrote ${target}`);
}
